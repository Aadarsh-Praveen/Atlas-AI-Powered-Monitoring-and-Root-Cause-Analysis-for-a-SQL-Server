"""Generates the files the Azure portal needs to create the collector's custom
tables in Log Analytics, from observability/schema.yml:

    observability/tables/<table>.json     a sample: a JSON array with one record
    observability/tables/transformations.kql
                                          one transformation per table, to paste
                                          into the wizard's transformation editor

Why both: the portal's "New custom log (DCR-based)" wizard builds the table
from a sample file, but Microsoft doesn't document how it guesses column types
(is 1 an int or a long? is a date string a datetime?). So the samples use
unambiguous values, AND each table's transformation converts every column to
its exact schema type (toint, tolong, toreal, tobool, todatetime, tostring).
The wizard shows the table's schema from the transformation's output, so the
result is exactly schema.yml, whatever the guess would have been.

Run it after changing schema.yml (from the repo root, any Python 3 with PyYAML):

    python observability/tools/make_table_files.py

It overwrites the generated files; commit them with the schema change.
Read-only otherwise: it touches nothing in Azure.
"""

import json
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
SCHEMA = REPO_ROOT / "observability" / "schema.yml"
OUT = REPO_ROOT / "observability" / "tables"

# A value of each type that can't be mistaken for another type.
SAMPLE_VALUES = {
    "string": "example",
    "int": 1,
    "long": 1,
    "real": 1.5,                          # a decimal point, so it's not taken for an integer
    "bool": True,
    "datetime": "2026-11-22T15:00:00.000000Z",
}

# KQL conversion function per schema type.
CONVERT = {
    "string": "tostring",
    "int": "toint",
    "long": "tolong",
    "real": "toreal",
    "bool": "tobool",
    "datetime": "todatetime",
}


def main() -> None:
    schema = yaml.safe_load(SCHEMA.read_text(encoding="utf-8"))
    OUT.mkdir(parents=True, exist_ok=True)
    sections = [
        "// observability/tables/transformations.kql",
        "// GENERATED by observability/tools/make_table_files.py from observability/schema.yml",
        f"// (schema version {schema['version']}). Don't edit by hand: change the schema and re-run.",
        "//",
        "// One transformation per custom table. In the portal's \"New custom log",
        "// (DCR-based)\" wizard, after uploading the table's sample file, open the",
        "// Transformation editor, replace its query with the table's section below",
        "// (from \"source\" to the end of the project list), and select Run, then Apply.",
        "// Each one converts every column to its exact type in schema.yml.",
        "",
    ]
    for name, table in schema["tables"].items():
        sample = {c["name"]: SAMPLE_VALUES[c["type"]] for c in table["columns"]}
        (OUT / f"{name}.json").write_text(json.dumps([sample], indent=2) + "\n", encoding="utf-8")

        columns = [f"{c['name']} = {CONVERT[c['type']]}({c['name']})" for c in table["columns"]]
        sections.append(f"// ---- {name} ({table['frequency']}) ----")
        sections.append("source")
        sections.append("| project\n    " + ",\n    ".join(columns))
        sections.append("")
    (OUT / "transformations.kql").write_text("\n".join(sections), encoding="utf-8")
    print(f"Wrote {len(schema['tables'])} samples and transformations.kql to {OUT}")


if __name__ == "__main__":
    main()
